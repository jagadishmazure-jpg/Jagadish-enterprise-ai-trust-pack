"""Model provenance: a sha256-pinned manifest of every component that shapes behaviour.

Components: base model, fine-tune, prompt template, guardrails. A change to any pinned file
without a new manifest entry fails CI (python -m trustpack.provenance.manifest --check).
"""
from __future__ import annotations

import json
import pathlib

from ..common import PKG, ROOT, sha256_hex

DIR = PKG / "provenance"
ARTIFACTS = DIR / "artifacts"
MANIFEST = DIR / "manifest.json"
HISTORY = DIR / "history"
CHANGELOG = DIR / "CHANGELOG.md"
REQUIRED = ("base_model", "fine_tune", "prompt_template", "guardrails")
FLOATING = {"latest", "main", "head", "*", ""}


def file_sha(path: pathlib.Path) -> str:
    return sha256_hex(path.read_bytes())


def load(path=MANIFEST) -> dict:
    return json.loads(pathlib.Path(path).read_text())


def verify(manifest: dict, root: pathlib.Path = ROOT, artifacts: pathlib.Path = ARTIFACTS) -> list[str]:
    errs = []
    comps = manifest.get("components", {})
    for name in REQUIRED:
        if name not in comps:
            errs.append(f"{name}: not in manifest")
    pinned_paths = set()
    for name, c in comps.items():
        if str(c.get("version", "")).lower() in FLOATING:
            errs.append(f"{name}: floating version '{c.get('version')}' (pin an exact version)")
        p = root / c["path"]
        pinned_paths.add(p.resolve())
        if not p.exists():
            errs.append(f"{name}: file {c['path']} missing")
            continue
        actual = file_sha(p)
        if c.get("sha256") != actual:
            errs.append(f"{name}: sha256 mismatch (pinned {str(c.get('sha256'))[:12]}, file {actual[:12]}) "
                        "- unpinned change")
    for f in sorted(artifacts.iterdir()):
        if f.is_file() and f.resolve() not in pinned_paths:
            errs.append(f"{f.name}: artifact not pinned in manifest")
    return errs


def compare(old: dict, new: dict) -> tuple[list[dict], list[str]]:
    """Return (changes, errors). Content changed with the same version string is an error."""
    changes, errs = [], []
    for name in sorted(set(old["components"]) | set(new["components"])):
        o, n = old["components"].get(name), new["components"].get(name)
        if o is None or n is None:
            changes.append({"component": name, "from": o and o["version"], "to": n and n["version"]})
            continue
        if o["sha256"] != n["sha256"]:
            if o["version"] == n["version"]:
                errs.append(f"{name}: content changed but version stayed '{n['version']}'")
            changes.append({"component": name, "from": o["version"], "to": n["version"]})
    if changes and old.get("release") == new.get("release"):
        errs.append(f"components changed but release stayed '{new.get('release')}'")
    return changes, errs


def changelog(history: list[dict]) -> str:
    lines = ["# Model provenance change log", "",
             "_Generated by `python -m trustpack provenance --changelog`. Do not edit by hand._", ""]
    pairs = list(zip(history[:-1], history[1:]))
    for old, new in reversed(pairs):  # newest first
        changes, _ = compare(old, new)
        lines.append(f"## {new['release']} ({new['date']})")
        lines.append("")
        lines += [f"- {c['component']}: {c['from']} -> {c['to']}" for c in changes] or ["- no component changes"]
        lines.append("")
    first = history[0]
    lines.append(f"## {first['release']} ({first['date']})")
    lines.append("")
    lines += [f"- {k}: {v['version']} (initial)" for k, v in sorted(first["components"].items())]
    return "\n".join(lines) + "\n"


def all_releases() -> list[dict]:
    hist = [load(p) for p in sorted(HISTORY.glob("*.json"))]
    return [*hist, load()]


def main(argv: list[str]) -> int:
    if "--changelog" in argv:
        text = changelog(all_releases())
        if "--check" in argv:
            ok = CHANGELOG.exists() and CHANGELOG.read_text() == text
            print("changelog up to date" if ok else "CHANGELOG.md is stale; run --changelog")
            return 0 if ok else 1
        CHANGELOG.write_text(text)
        print(f"wrote {CHANGELOG.relative_to(ROOT)}")
        return 0
    m = load()
    errs = verify(m)
    rels = all_releases()
    _, cmp_errs = compare(rels[-2], rels[-1]) if len(rels) > 1 else ([], [])
    errs += cmp_errs
    print(f"release {m['release']}: {len(m['components'])} pinned components")
    for k, c in sorted(m["components"].items()):
        print(f"  {k:<16} {c['source']:<9} {c['version']:<12} sha256:{c['sha256'][:16]}")
    print("provenance check: " + ("PASS" if not errs else "FAIL"))
    for e in errs:
        print(f"  {e}")
    return 1 if errs else 0

